#!/usr/bin/env node
// Deep upstream audit: clone/pull the three repos into .cache/repos (git-ignored),
// run each repo's cheapest trustworthy gate, and write docs/audit-latest.{json,md}.
// Network or tool absence is reported as `unverified` — never as green.
import { execFileSync } from "node:child_process";
import { existsSync, mkdirSync, writeFileSync } from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const ROOT = path.join(path.dirname(fileURLToPath(import.meta.url)), "..");
const CACHE = path.join(ROOT, ".cache", "repos");
const REPOS = [
  { name: "back", url: "https://github.com/salimipuria-blip/back.git", gate: null },
  { name: "bison-brand-book", url: "https://github.com/salimipuria-blip/bison-brand-book.git", gate: "npm test" },
  { name: "MegaSkillClaude", url: "https://github.com/salimipuria-blip/MegaSkillClaude.git", gate: "node scripts/doctor.mjs --list" },
];

function sh(cmd, args, cwd) {
  try { return { ok: true, out: execFileSync(cmd, args, { cwd, encoding: "utf8", timeout: 600_000 }).trim() }; }
  catch (e) { return { ok: false, out: String(e.stdout ?? e.message).trim().slice(-2000) }; }
}

mkdirSync(CACHE, { recursive: true });
const report = { generated_at: new Date().toISOString(), repos: [] };
for (const repo of REPOS) {
  const dir = path.join(CACHE, repo.name);
  const sync = existsSync(path.join(dir, ".git")) ? sh("git", ["-C", dir, "pull", "--ff-only"], ROOT) : sh("git", ["clone", "--depth", "50", repo.url, dir], ROOT);
  const head = sync.ok ? sh("git", ["-C", dir, "log", "-1", "--format=%h %cs %s"], ROOT) : { ok: false, out: "clone/pull failed" };
  const gate = sync.ok && repo.gate ? sh("bash", ["-c", repo.gate], dir) : { ok: null, out: repo.gate ? "skipped (sync failed)" : "no cheap gate defined" };
  report.repos.push({ name: repo.name, url: repo.url.replace(/\.git$/, ""), head: head.out, gate: repo.gate,
    status: !sync.ok ? "unverified" : gate.ok === null ? "synced" : gate.ok ? "pass" : "fail", gate_tail: gate.out.split("\n").slice(-8).join("\n") });
  console.log(`${repo.name}: ${report.repos.at(-1).status} @ ${head.out}`);
}
writeFileSync(path.join(ROOT, "docs", "audit-latest.json"), JSON.stringify(report, null, 2) + "\n");
writeFileSync(path.join(ROOT, "docs", "audit-latest.md"),
  `# Latest upstream audit — ${report.generated_at}\n\n` +
  report.repos.map((r) => `- **${r.name}** (${r.status}) \`${r.head}\` — gate: \`${r.gate ?? "—"}\``).join("\n") +
  `\n\nGenerated by \`node tools/audit-repos.mjs\`. \`unverified\` means the check did not run here; it is not a pass.\n`);
console.log("Wrote docs/audit-latest.{json,md}");
